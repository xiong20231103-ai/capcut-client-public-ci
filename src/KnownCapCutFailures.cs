        public static IList<KnownCapCutFailure> All
        {
            get { return all.ToList(); }
        }

        public static string Match(string message)
        {
            string text = message ?? "";
            KnownCapCutFailure match = all.FirstOrDefault(item =>
                text.IndexOf(item.Trigger,
                    StringComparison.OrdinalIgnoreCase) >= 0);
            return match == null ? "" : match.Fingerprint;
        }

        private static KnownCapCutFailure Item(string fingerprint,
            string trigger, string regression, bool blocks)
        {
            return new KnownCapCutFailure {
                Fingerprint = fingerprint,
                Trigger = trigger,
                Regression = regression,
                BlocksDownstream = blocks
            };
        }
