    internal static class ExportEntitlementPolicy
    {
        internal static bool IsBlockingPrompt(string visibleText)
        {
            string text = new string((visibleText ?? "").Where(c => !Char.IsWhiteSpace(c)).ToArray()).ToLowerInvariant();
            bool heading = text.Contains("您正在使用") && text.Contains("pro权益") ||
                // Observed Windows OCR spellings from the retained incident image.
                text.Contains("您止在便用") && text.Contains("pro功能") ||
                text.Contains("您止在使用") && text.Contains("pro权益") ||
                text.Contains("you'reusingpro") || text.Contains("youareusingpro");
            bool action = text.Contains("获得免费pro") || text.Contains("getdiscount") ||
                text.Contains("upgrade") || text.Contains("joinpro");
            return heading && action;
        }

        internal static CapCutOperationFailure Failure()
        {
            return new CapCutOperationFailure("export", "CAPCUT_PRO_ENTITLEMENT_BLOCKED",
                CapCutFailureClassification.UserActionRequired,
                "CapCut导出被Pro权益弹窗阻止；账号登录不等于本会话权益校验通过。请核验团队权益；草稿保留，不购买、不移除字幕、不重复点击导出。");
        }
    }

